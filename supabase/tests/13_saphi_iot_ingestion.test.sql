begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select plan(14);
select ok(exists(select 1 from pg_roles where rolname='saphi_ingest' and not rolsuper and not rolbypassrls),'machine role cannot bypass RLS');
select ok(not has_table_privilege('saphi_ingest','saphi.devices','SELECT'),'service cannot enumerate devices');
select ok(not has_table_privilege('saphi_ingest','saphi.sensor_readings','SELECT'),'service cannot read measurements');
select ok(not has_table_privilege('saphi_ingest','saphi.sensor_readings','INSERT'),'service cannot insert outside function');
select ok(not has_table_privilege('saphi_ingest','saphi.iot_bindings','SELECT'),'service cannot enumerate bindings');
select ok(not has_table_privilege('saphi_ingest','saphi.iot_bindings','UPDATE'),'service cannot change binding');
select ok(not has_table_privilege('app_api','saphi.iot_bindings','SELECT'),'human API cannot enumerate certificate bindings');
select ok(not has_table_privilege('app_api','saphi.sensor_readings','INSERT'),'human API still cannot ingest');
select ok(not has_table_privilege('app_auth','saphi.iot_receipts','SELECT'),'auth cannot read receipts');
select ok(has_function_privilege('saphi_ingest','saphi.ingest_iot(jsonb,text)','EXECUTE'),'machine may call narrow function');
select ok(not has_function_privilege('app_api','saphi.ingest_iot(jsonb,text)','EXECUTE'),'human API cannot call function');
select ok(not has_function_privilege('app_auth','saphi.ingest_iot(jsonb,text)','EXECUTE'),'auth cannot call function');
select ok((select relrowsecurity from pg_class where oid='saphi.iot_bindings'::regclass),'binding RLS enabled');
select ok((select relrowsecurity from pg_class where oid='saphi.iot_receipts'::regclass),'receipt RLS enabled');
select * from finish();
rollback;
