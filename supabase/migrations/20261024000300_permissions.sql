-- Profiles, hierarchical menus, actions and permissions (permission = menu + action).

create table app.profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 100),
  description text check (length(description) <= 500),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references app.users (id) default app.current_user_id(),
  updated_at timestamptz not null default now(),
  updated_by uuid references app.users (id) default app.current_user_id()
);

create unique index profiles_name_key on app.profiles (lower(name));

create trigger profiles_set_updated before update on app.profiles
  for each row execute function app.set_updated();

create table app.user_profiles (
  user_id uuid not null references app.users (id),
  profile_id uuid not null references app.profiles (id),
  granted_at timestamptz not null default now(),
  granted_by uuid references app.users (id) default app.current_user_id(),
  primary key (user_id, profile_id)
);

create index user_profiles_profile_idx on app.user_profiles (profile_id);

create table app.menus (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references app.menus (id),
  kind text not null check (kind in ('module', 'menu', 'submenu')),
  code text not null unique check (code ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$' and length(code) <= 100),
  name jsonb not null check (app.is_i18n(name)),
  icon text check (length(icon) <= 64),
  route text check (route ~ '^/[a-z0-9/_-]*$' and length(route) <= 200),
  sort_order integer not null default 0,
  show_in_mobile boolean not null default false,
  superuser_only boolean not null default false,
  is_system boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references app.users (id) default app.current_user_id(),
  updated_at timestamptz not null default now(),
  updated_by uuid references app.users (id) default app.current_user_id(),
  check ((kind = 'module') = (parent_id is null)),
  check (kind <> 'module' or route is null)
);

create index menus_parent_idx on app.menus (parent_id, sort_order);

create trigger menus_set_updated before update on app.menus
  for each row execute function app.set_updated();

-- Hierarchy is fixed: module > menu > submenu (which also makes cycles impossible).
-- System menus keep their code and cannot be deleted.
create function app.menus_guard() returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_kind text;
begin
  if tg_op = 'DELETE' then
    if old.is_system then
      raise exception 'system menus cannot be deleted' using errcode = '42501';
    end if;
    return old;
  end if;

  if tg_op = 'UPDATE' and old.is_system and (new.code <> old.code or not new.is_system) then
    raise exception 'system menu code cannot change' using errcode = '42501';
  end if;

  if new.parent_id is not null then
    select kind into parent_kind from app.menus where id = new.parent_id;
    if (new.kind = 'menu' and parent_kind <> 'module') or (new.kind = 'submenu' and parent_kind <> 'menu') then
      raise exception 'invalid menu hierarchy' using errcode = '23514';
    end if;
  end if;
  return new;
end
$$;

create trigger menus_guard before insert or update or delete on app.menus
  for each row execute function app.menus_guard();

create table app.actions (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z][a-z0-9_]*$' and length(code) <= 50),
  name jsonb not null check (app.is_i18n(name)),
  is_standard boolean not null default false,
  sort_order integer not null default 0
);

create table app.menu_actions (
  id uuid primary key default gen_random_uuid(),
  menu_id uuid not null references app.menus (id),
  action_id smallint not null references app.actions (id),
  unique (menu_id, action_id)
);

create table app.profile_permissions (
  profile_id uuid not null references app.profiles (id),
  menu_action_id uuid not null references app.menu_actions (id),
  granted_at timestamptz not null default now(),
  granted_by uuid references app.users (id) default app.current_user_id(),
  primary key (profile_id, menu_action_id)
);

create index profile_permissions_menu_action_idx on app.profile_permissions (menu_action_id);

-- A menu is effective when it and all its ancestors are active; superuser_only is inherited.
create view app.v_effective_menus with (security_invoker = true) as
select
  m.id,
  m.code,
  m.superuser_only or coalesce(p1.superuser_only, false) or coalesce(p2.superuser_only, false) as superuser_only
from app.menus m
left join app.menus p1 on p1.id = m.parent_id
left join app.menus p2 on p2.id = p1.parent_id
where m.is_active and coalesce(p1.is_active, true) and coalesce(p2.is_active, true);

-- Effective permissions: superusers get everything; others the union of their active profiles,
-- never including superuser-only menus. Inactive users get nothing.
create view app.v_user_permissions with (security_invoker = true) as
select u.id as user_id, ma.id as menu_action_id, m.code as menu_code, a.code as action_code
from app.users u
join app.roles r on r.id = u.role_id and r.code = 'superuser'
cross join app.v_effective_menus m
join app.menu_actions ma on ma.menu_id = m.id
join app.actions a on a.id = ma.action_id
where u.status = 'active'
union
select u.id, ma.id, m.code, a.code
from app.users u
join app.roles r on r.id = u.role_id and r.code <> 'superuser'
join app.user_profiles up on up.user_id = u.id
join app.profiles p on p.id = up.profile_id and p.is_active
join app.profile_permissions pp on pp.profile_id = p.id
join app.menu_actions ma on ma.id = pp.menu_action_id
join app.v_effective_menus m on m.id = ma.menu_id and not m.superuser_only
join app.actions a on a.id = ma.action_id
where u.status = 'active';
